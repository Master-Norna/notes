"""Explicit dependency preparation only. run.py never calls this script or pip."""
from __future__ import annotations
import argparse
import hashlib
from pathlib import Path
import subprocess
import sys
import venv

HERE = Path(__file__).resolve().parent


def main():
    p = argparse.ArgumentParser(description=__doc__)
    mode = p.add_mutually_exclusive_group(required=True)
    mode.add_argument("--download-to", type=Path, help="NETWORK: download fixed wheels for this Python/platform")
    mode.add_argument("--venv", type=Path, help="create/use an isolated dependency environment")
    p.add_argument("--wheelhouse", type=Path, help="install strictly offline from this directory")
    p.add_argument("--allow-network", action="store_true", help="explicitly permit pip index access when installing")
    args = p.parse_args()
    if sys.version_info[:2] != (3, 12):
        p.error("The recorded environment is Python 3.12; use it for preparation and execution.")
    if args.download_to:
        if args.wheelhouse or args.allow_network:
            p.error("--download-to is already an explicit network operation; no other options needed")
        args.download_to.mkdir(parents=True, exist_ok=True)
        subprocess.run([sys.executable, "-m", "pip", "download", "--disable-pip-version-check", "--only-binary=:all:", "--no-deps", "-r", str(HERE / "requirements.lock"), "-d", str(args.download_to)], check=True)
        lines = [hashlib.sha256(f.read_bytes()).hexdigest() + "  " + f.name for f in sorted(args.download_to.glob("*.whl"))]
        (args.download_to / "SHA256SUMS.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
        print("Downloaded fixed-version wheels; keep SHA256SUMS.txt with the wheelhouse.")
        return
    if bool(args.wheelhouse) == bool(args.allow_network):
        p.error("Choose exactly one: --wheelhouse (offline) or --allow-network (online preparation)")
    if args.wheelhouse:
        sums = args.wheelhouse / "SHA256SUMS.txt"
        if not sums.is_file():
            p.error("wheelhouse must include SHA256SUMS.txt generated by --download-to")
        for line in sums.read_text(encoding="utf-8").splitlines():
            digest, name = line.split("  ", 1)
            if Path(name).name != name:
                p.error("Unsafe wheel filename in checksum manifest")
            if hashlib.sha256((args.wheelhouse / name).read_bytes()).hexdigest() != digest:
                p.error(f"Wheel checksum mismatch: {name}")
    executable = args.venv / ("Scripts/python.exe" if sys.platform == "win32" else "bin/python")
    if not executable.is_file():
        venv.EnvBuilder(with_pip=True).create(args.venv)
    command = [str(executable), "-m", "pip", "install", "--disable-pip-version-check", "--no-deps", "-r", str(HERE / "requirements.lock")]
    if args.wheelhouse:
        command.extend(["--no-index", "--find-links", str(args.wheelhouse)])
    subprocess.run(command, check=True)
    subprocess.run([str(executable), "-m", "pip", "check"], check=True)
    print(f"Ready. Run with {executable} (no activation needed).")


if __name__ == "__main__":
    main()
