// Extract `remove_impl` from the fixed upstream snapshots in `upstream/`.
// Nothing is hand-copied: the function body is taken verbatim, only its
// visibility is changed so the demo modules can call it.

use std::env;
use std::fs;
use std::path::PathBuf;

const VERSIONS: &[(&str, &str)] = &[
    ("old_parent", "old-parent"),
    ("old_merge", "old-merge"),
    ("merge_parent", "merge-parent"),
    ("first", "first"),
    ("merge", "merge"),
];

fn extract(source: &str) -> String {
    let start = source
        .find("fn remove_impl(")
        .expect("remove_impl not found in upstream snapshot");

    let bytes = source.as_bytes();
    let mut open = start;
    while bytes[open] != b'{' {
        open += 1;
    }

    let mut depth = 0i32;
    let mut close = None;
    for (index, byte) in bytes.iter().enumerate().skip(open) {
        match byte {
            b'{' => depth += 1,
            b'}' => {
                depth -= 1;
                if depth == 0 {
                    close = Some(index);
                    break;
                }
            }
            _ => {}
        }
    }
    let close = close.expect("unbalanced braces in remove_impl");

    source[start..=close].replacen(
        "fn remove_impl(",
        "pub fn remove_impl(",
        1,
    )
}

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let mut generated = String::from(
        "// Generated by build.rs from the fixed upstream snapshots.\n",
    );

    for (module, directory) in VERSIONS {
        let path = manifest.join("upstream").join(directory).join("remove.rs");
        println!("cargo:rerun-if-changed={}", path.display());
        let source = fs::read_to_string(&path)
            .unwrap_or_else(|error| panic!("cannot read {}: {error}", path.display()));
        generated.push_str(&format!(
            "\npub mod {module} {{\n    use crate::{{Arguments, Span, Value}};\n\n{}\n}}\n",
            extract(&source)
        ));
    }

    println!("cargo:rerun-if-changed=build.rs");
    let out = PathBuf::from(env::var("OUT_DIR").unwrap()).join("extracted.rs");
    fs::write(&out, generated).expect("cannot write extracted.rs");
}
