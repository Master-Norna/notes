def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()[:12]


def run_case(guard, relpath: str, content: str) -> dict[str, object]:
    with tempfile.TemporaryDirectory() as tmp:
        target = Path(tmp) / relpath
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8", newline="\n")
        before = target.read_bytes()
        if guard(relpath):
            return {
                "result": "refused",
                "exit": 2,
                "before": digest(before),
                "after": digest(before),
                "bytes": len(before),
            }
        target.write_text(SBOM_TEXT, encoding="utf-8", newline="\n")
        after = target.read_bytes()
        return {
            "result": "overwritten",
            "exit": 0,
            "before": digest(before),
            "after": digest(after),
            "bytes": len(before),
        }


def evaluate() -> dict[str, object]:
    rows = []
    for name, ecosystem, kind, content in INPUTS:
        rows.append(
            {
                "name": name,
                "ecosystem": ecosystem,
                "kind": kind,
                "parent": run_case(guard_parent, name, content),
                "merged": run_case(guard_merged, name, content),
            }
        )
    extras = []
    for name, note, kind in EXTRA_CASES:
        extras.append(
            {
                "name": name,
                "note": note,
                "kind": kind,
                "parent": run_case(guard_parent, name, "original bytes\n"),
                "merged": run_case(guard_merged, name, "original bytes\n"),
            }
        )
    return {"inputs": rows, "extras": extras}


def summary(rows: list[dict[str, object]], key: str) -> dict[str, int]:
    overwritten = [r for r in rows if r[key]["result"] == "overwritten"]  # type: ignore[index]
    manifest = [r for r in overwritten if r["kind"] == "manifest"]
    return {
        "total": len(rows),
        "overwritten": len(overwritten),
        "refused": len(rows) - len(overwritten),
        "manifests_lost": len(manifest),
        "lockfiles_lost": len(overwritten) - len(manifest),
    }


def print_table(result: dict[str, object]) -> None:
    rows = result["inputs"]  # type: ignore[index]
    print(f"{'name':<20}{'ecosystem':<12}{'kind':<10}{'parent':<14}{'merged':<14}")
    print("-" * 70)
    for row in rows:
        print(
            f"{row['name']:<20}{row['ecosystem']:<12}{row['kind']:<10}"
            f"{row['parent']['result']:<14}{row['merged']['result']:<14}"
        )
    print()
    for key in ("parent", "merged"):
        s = summary(rows, key)
        print(
            f"{key:<8} overwrites {s['overwritten']}/{s['total']} dependency inputs "
            f"({s['manifests_lost']} manifests, {s['lockfiles_lost']} lockfiles)"
        )
    print()
    print(f"{'extra case':<20}{'parent':<14}{'merged':<14}note")
    print("-" * 78)
    for row in result["extras"]:  # type: ignore[index]
        print(
            f"{row['name']:<20}{row['parent']['result']:<14}"
            f"{row['merged']['result']:<14}{row['note']}"
        )


def test(result: dict[str, object]) -> int:
    rows = result["inputs"]  # type: ignore[index]
    extras = {r["name"]: r for r in result["extras"]}  # type: ignore[index]
    failures = []

    def check(cond: bool, message: str) -> None:
        if not cond:
            failures.append(message)

    parent = summary(rows, "parent")
    merged = summary(rows, "merged")
    check(parent["overwritten"] == 13, f"parent should overwrite 13, got {parent['overwritten']}")
    check(parent["manifests_lost"] == 6, f"parent should lose 6 manifests, got {parent['manifests_lost']}")
    check(merged["overwritten"] == 0, f"merged should overwrite 0, got {merged['overwritten']}")
    check(merged["refused"] == 24, f"merged should refuse 24, got {merged['refused']}")

    for name in ("requirements.txt", "package.json", "uv.lock"):
        row = next(r for r in rows if r["name"] == name)
        check(row["parent"]["result"] == "refused", f"{name} was already protected before")
        check(row["merged"]["result"] == "refused", f"{name} stays protected")

    for name, want_parent, want_merged in [
        ("sub/Cargo.lock", "overwritten", "refused"),
        ("CARGO.LOCK", "overwritten", "refused"),
        ("Composer.JSON", "overwritten", "refused"),
        ("App.csproj", "refused", "refused"),
        ("App.CSPROJ", "refused", "refused"),
        ("sbom.json", "overwritten", "overwritten"),
        ("report/bom.json", "overwritten", "overwritten"),
        ("pins.txt", "overwritten", "overwritten"),
    ]:
        row = extras[name]
        check(row["parent"]["result"] == want_parent, f"{name} parent should be {want_parent}")
        check(row["merged"]["result"] == want_merged, f"{name} merged should be {want_merged}")

    for row in rows:
        for key in ("parent", "merged"):
            case = row[key]
            if case["result"] == "overwritten":
                check(case["before"] != case["after"], f"{row['name']} {key}: bytes did not change")
            else:
                check(case["before"] == case["after"], f"{row['name']} {key}: refused but bytes changed")

    if failures:
        for message in failures:
            print(f"FAIL {message}", file=sys.stderr)
        return 1
    print(
        f"PASS parent overwrites {parent['overwritten']}/24 inputs, "
        f"merged {merged['overwritten']}/24; extras and byte checks pass"
    )
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json", action="store_true", help="print JSON")
    parser.add_argument("--test", action="store_true", help="run assertions")
    args = parser.parse_args()

    result = evaluate()
    if args.test:
        return test(result)
    if args.json:
        print(json.dumps(result, indent=2))
    else:
        print_table(result)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
