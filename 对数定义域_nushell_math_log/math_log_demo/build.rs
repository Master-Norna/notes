// Extract `require_*` and `operate` from the fixed upstream snapshots in
// `upstream/`. Nothing is hand-copied: the function bodies are taken
// verbatim, only their visibility is changed so the demo can call them.

use std::env;
use std::fs;
use std::path::PathBuf;

/// (module, directory, name of the validation helper)
const VERSIONS: &[(&str, &str, &str)] = &[
    ("parent", "parent", "require_positive_base"),
    ("first", "first", "require_positive_base"),
    ("merge", "merge", "require_valid_base"),
];

fn extract(source: &str, name: &str) -> String {
    let marker = format!("fn {name}(");
    let start = source
        .find(&marker)
        .unwrap_or_else(|| panic!("{name} not found in upstream snapshot"));

    let bytes = source.as_bytes();
    let mut open = start;
    while bytes[open] != b'{' {
        open += 1;
    }

    let mut depth = 0i32;
    let mut close = None;
    for (index, byte) in bytes.iter().enumerate().skip(open) {
        match byte {
            b'{' => depth += 1,
            b'}' => {
                depth -= 1;
                if depth == 0 {
                    close = Some(index);
                    break;
                }
            }
            _ => {}
        }
    }
    let close = close.unwrap_or_else(|| panic!("unbalanced braces in {name}"));

    source[start..=close].replacen(&marker, &format!("pub {marker}"), 1)
}

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let mut generated =
        String::from("// Generated by build.rs from the fixed upstream snapshots.\n");

    for (module, directory, checker) in VERSIONS {
        let path = manifest.join("upstream").join(directory).join("log.rs");
        println!("cargo:rerun-if-changed={}", path.display());
        let source = fs::read_to_string(&path)
            .unwrap_or_else(|error| panic!("cannot read {}: {error}", path.display()));
        generated.push_str(&format!(
            "\npub mod {module} {{\n    use crate::{{ShellError, Span, Spanned, Value}};\n\n{}\n\n{}\n}}\n",
            extract(&source, checker),
            extract(&source, "operate")
        ));
    }

    println!("cargo:rerun-if-changed=build.rs");
    let out = PathBuf::from(env::var("OUT_DIR").unwrap()).join("extracted.rs");
    fs::write(&out, generated).expect("cannot write extracted.rs");
}
